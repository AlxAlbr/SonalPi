import { expect, test } from '@playwright/test'
import { ouvrirAnalyse, ouvrirSurCorpus, selectionner } from './util'

test('Lexico → source → cas → source se dépile avec les sélections, filtres et défilements', async () => {
  const { app, page } = await ouvrirSurCorpus('sonal-retours-')
  try {
    await page.setViewportSize({ width: 1100, height: 620 })
    await ouvrirAnalyse(page, 'lexico')
    const lexico = page.locator('.panneau-lexico')
    await lexico.getByLabel('Rechercher une forme').fill('a')
    await lexico.getByRole('button', { name: 'Forme', exact: true }).click()
    await lexico.getByRole('cell', { name: 'travail', exact: true }).click()
    const concordance = lexico.locator('.concordance').first()
    await concordance.scrollIntoViewIfNeeded()
    const lignes = await lexico.locator('tbody').innerText()
    const defilement = await lexico.locator('.resultats').evaluate((el) => el.scrollTop)
    await concordance.click()
    await expect(page.locator('.entretien-ecran')).toBeVisible()
    await expect(page.getByRole('button', { name: /Revenir à Lexico/ })).toBeVisible()

    await selectionner(page, 'travail passé')
    const centre = await page.evaluate(() => {
      const plage = window.getSelection()!.getRangeAt(0).getBoundingClientRect()
      return { x: plage.x + plage.width / 2, y: plage.y + plage.height / 2 }
    })
    await page.mouse.click(centre.x, centre.y, { button: 'right' })
    await page.getByRole('menuitem', { name: /Associer à un cas/ }).click()
    const dialogue = page.getByRole('dialog', { name: 'Ajouter à un cas', exact: true })
    await dialogue.getByRole('button', { name: 'Créer un nouveau cas', exact: true }).click()
    await dialogue.getByLabel('Nom du nouveau cas *').fill('Parcours lié')
    await dialogue.getByRole('button', { name: 'Créer et associer', exact: true }).click()
    await expect(page.locator('.entretien-ecran')).toBeVisible()
    await page.getByRole('button', { name: 'Ouvrir le cas « Parcours lié »', exact: true }).click()
    const cas = page.locator('.cas-corpus')
    await expect(cas.getByLabel('Nom du cas', { exact: true })).toHaveValue('Parcours lié')
    await cas.getByLabel('Rechercher un cas').fill('lié')
    await cas.getByRole('button', { name: 'Voir dans l’entretien' }).click()
    await expect(page.locator('.entretien-ecran')).toBeVisible()
    await page.locator('.editeur').press('Control+Home')
    await page.keyboard.insertText('Préambule ajouté. ')
    await expect(page.locator('.tete .etat')).toHaveText('à jour')
    await page.getByRole('button', { name: /Revenir au cas « Parcours lié »/ }).click()
    await expect(cas.getByLabel('Rechercher un cas')).toHaveValue('lié')
    await expect(cas.getByLabel('Nom du cas', { exact: true })).toHaveValue('Parcours lié')
    await page.getByRole('button', { name: /Revenir au passage/ }).click()
    await expect(page.locator('.editeur')).toBeFocused()
    expect(await page.evaluate(() => window.getSelection()?.toString())).toBe('travail passé')
    await page.getByRole('button', { name: /Revenir à Lexico/ }).click()
    await expect(lexico).toBeVisible()
    await expect(lexico.getByLabel('Rechercher une forme')).toHaveValue('a')
    await expect(lexico.locator('tbody')).toHaveText(lignes, { useInnerText: true })
    await expect(lexico.locator('tr.selectionnee')).toContainText('travail')
    expect(await lexico.locator('.resultats').evaluate((el) => el.scrollTop)).toBe(defilement)
    await expect(page.locator('.retour-contexte')).toHaveCount(0)
    await expect(lexico).toContainText('Les sources ont changé.')

    await lexico.getByRole('button', { name: 'Actualiser', exact: true }).click()
    await lexico.locator('.concordance').first().click()
    await expect(page.locator('.retour-contexte')).toBeVisible()
    await page.getByRole('button', { name: 'Organiser & Exporter', exact: true }).click()
    await expect(page.locator('.retour-contexte')).toHaveCount(0)
  } finally {
    await app.close()
  }
})
