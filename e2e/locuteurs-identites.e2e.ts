import { test, expect } from '@playwright/test'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { entrerCorpus, lancer, ouvrirDetailsLocuteurs, retourCorpus, regulariserDansEntretien } from './util'

test('locuteurs : régulariser, renommer, réunir, consulter les notes et dissocier sans ancien répertoire', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'sonal-locuteurs-parcours-')), app = await lancer(dir)
  try {
    const page = await app.firstWindow(); await entrerCorpus(page)
    await page.evaluate(async () => {
      const api = window.sonal.corpus, { id } = await api.creerEntretienVide('Deuxième entretien'), r = await api.lireEntretien(id)
      if (!r.ok) throw new Error('Fixture absente')
      const { formatVersion: _v, lastModified: _d, ...payload } = r.data
      payload.participations = [{ id: 'local', index: 0, nom: 'Mme Dupont', valeursLoc: {}, locuteurRef: null }]
      await api.ecrireEntretien(id, payload)
    })
    await regulariserDansEntretien(page, 'Entretien Karine', 'Karine')
    await regulariserDansEntretien(page, 'Deuxième entretien', 'Mme Dupont')
    await ouvrirDetailsLocuteurs(page)
    const panneau = page.locator('.locuteurs-corpus'), details = panneau.locator('.details-locuteurs')
    const ligne = (nom: string) => panneau.getByRole('option').filter({ has: page.getByText(nom, { exact: true }) })
    await expect(panneau.locator('.personnes-corpus')).toHaveCount(0)
    await expect(panneau.getByLabel('Nouvelle personne', { exact: true })).toHaveCount(0)
    await ligne('Karine').click()
    await panneau.getByRole('button', { name: 'Renommer…', exact: true }).click()
    const renommage = page.getByRole('dialog', { name: 'Renommer ce locuteur', exact: true })
    await renommage.getByLabel('Nouveau nom').fill('K. Dupont')
    await renommage.getByRole('button', { name: 'Renommer dans tous les entretiens' }).click(); await expect(renommage).toHaveCount(0)
    await ligne('Mme Dupont').click({ modifiers: ['Control'] })
    await panneau.getByRole('button', { name: 'C’est le même locuteur…' }).click()
    const reunir = page.getByRole('dialog', { name: 'Réunir les locuteurs sélectionnés' })
    await reunir.getByLabel('Nom commun', { exact: true }).fill('K. Dupont')
    await reunir.getByRole('radio', { name: 'Conserver les noms actuels', exact: true }).check()
    await reunir.getByRole('button', { name: 'Réunir les locuteurs', exact: true }).click(); await expect(reunir).toHaveCount(0)
    await expect(details.getByRole('heading', { name: 'K. Dupont · Entretien Karine', exact: true })).toBeVisible()
    await expect(details.getByRole('heading', { name: 'Mme Dupont · Deuxième entretien', exact: true })).toBeVisible()
    await details.getByRole('button', { name: 'Ouvrir les locuteurs de Entretien Karine', exact: true }).click()
    await expect(page.locator('.entretien-ecran')).toBeVisible()
    await expect(page.locator('.entretien-ecran button[data-onglet="locuteurs"].actif')).toHaveAttribute('title', /^Locuteurs(?: —|$)/)
    await page.locator('.entretien-ecran button[data-onglet="notes"]').click()
    const formulaire = page.locator('.nouvelle-note-inline')
    await expect(formulaire.locator('.champ-titre-note input')).toHaveValue('')
    await expect(formulaire.locator('.champ-titre-note input')).not.toHaveAttribute('placeholder')
    await expect(formulaire.getByRole('combobox', { name: /^Catégorie/ })).toHaveValue('ncat_generale')
    await formulaire.locator('.champ-titre-note input').fill('Identité vérifiée')
    await formulaire.getByRole('button', { name: '🔗 Lier à un locuteur', exact: true }).click()
    const choix = page.getByRole('dialog', { name: 'Lier à un locuteur', exact: true })
    await choix.getByRole('checkbox', { name: 'K. Dupont', exact: true }).check(); await page.keyboard.press('Escape')
    await formulaire.getByRole('button', { name: '🔗 Lier à un locuteur', exact: true }).click()
    await expect(choix.getByRole('checkbox', { name: 'K. Dupont', exact: true })).toBeChecked(); await page.keyboard.press('Escape')
    await formulaire.getByRole('button', { name: 'Créer une note', exact: true }).click()
    await retourCorpus(page)
    await expect(details.getByRole('heading', { name: 'Identité vérifiée · Entretien Karine', exact: true })).toBeVisible()
    await details.getByRole('button', { name: 'Ouvrir les notes de Entretien Karine', exact: true }).click()
    await expect(page.locator('.entretien-ecran button[data-onglet="notes"].actif')).toHaveAttribute('title', /^Notes(?: —|$)/)
    await retourCorpus(page)
    await panneau.getByRole('button', { name: 'Dissocier…', exact: true }).click()
    const dissocier = page.getByRole('dialog', { name: 'Dissocier ce locuteur' })
    await dissocier.getByRole('checkbox', { name: 'Entretien Karine · K. Dupont', exact: true }).check()
    await dissocier.getByRole('button', { name: 'Annuler', exact: true }).click()
    await panneau.getByRole('button', { name: 'Dissocier…', exact: true }).click()
    await dissocier.getByRole('checkbox', { name: 'Entretien Karine · K. Dupont', exact: true }).check()
    await dissocier.getByRole('button', { name: 'Dissocier les entretiens cochés' }).click(); await expect(dissocier).toHaveCount(0)
    await details.getByRole('button', { name: 'Ouvrir les locuteurs de Entretien Karine', exact: true }).click()
    await page.getByRole('button', { name: 'Modifier les locuteurs', exact: true }).click()
    const champs = page.locator('.nom-loc').filter({ visible: true })
    const index = await champs.evaluateAll((inputs) => inputs.findIndex((input) => (input as HTMLInputElement).value === 'K. Dupont'))
    expect(index).toBeGreaterThanOrEqual(0)
    const nom = champs.nth(index)
    await expect(nom).toHaveValue('K. Dupont'); await nom.fill('Karine Durand'); await nom.press('Enter')
    const global = page.getByRole('dialog', { name: 'Renommer ce locuteur dans les entretiens', exact: true })
    await expect(nom).toHaveValue('Karine Durand'); await expect(nom).toBeEnabled()
    await expect(global).toHaveCount(0)
    await page.getByRole('button', { name: 'Fermer la gestion des locuteurs' }).click(); await retourCorpus(page)
    const inv = await page.evaluate(() => window.sonal.corpus.inventaireIdentitesLocuteurs())
    expect(inv.locuteurs).toHaveLength(2)
    const karine = inv.participations.find((p) => p.nom === 'Karine Durand')!, autre = inv.participations.find((p) => p.nom === 'Mme Dupont')!
    expect(karine.locuteurRef).toBeTruthy(); expect(karine.locuteurRef).not.toBe(autre.locuteurRef)
    expect(inv.notes.find((n) => n.titre === 'Identité vérifiée')?.participationIds).toContain(karine.participationId)
    await expect(panneau.getByRole('separator')).toHaveCount(1)
    await page.setViewportSize({ width: 650, height: 850 })
    const cadre = await details.boundingBox(); expect(cadre!.x).toBeGreaterThanOrEqual(0); expect(cadre!.x + cadre!.width).toBeLessThanOrEqual(651)
  } finally { await app.close(); rmSync(dir, { recursive: true, force: true }) }
})
