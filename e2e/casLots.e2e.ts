import { test, expect } from '@playwright/test'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { entrerCorpus, lancer } from './util'

test('30 personnes donnent 30 cas ou un collectif, avec aperçu annulable et identités persistantes', async () => {
  const userDataDir = mkdtempSync(join(tmpdir(), 'sonal-cas-lots-'))
  let app = await lancer(userDataDir)
  try {
    let page = await app.firstWindow()
    await entrerCorpus(page)
    await page.evaluate(async () => {
      const api = (window as any).sonal.corpus
      for (let index = 0; index < 30; index++) {
        await api.personnesCommander({ type: 'creerDefinition', nom: index < 2 ? 'Homonyme' : `Personne ${index}` }, true)
      }
    })
    await page.locator('.btn-cas').click()
    let modale = page.locator('.modale-cas')
    const fichier = join(userDataDir, 'corpus', 'corpus.json')
    const source = join(userDataDir, 'corpus', 'entretiens', 'e1.json')
    const avant = readFileSync(fichier, 'utf8')
    const sourceAvant = readFileSync(source, 'utf8')
    await modale.getByRole('button', { name: 'Nouveau cas' }).click()
    await modale.getByRole('radio', { name: 'Plusieurs personnes' }).check()
    await modale.getByRole('button', { name: 'Tout sélectionner', exact: true }).click()
    await expect(modale.locator('.actions-selection')).toContainText('30 sélectionné(s)')
    await modale.getByRole('button', { name: 'Prévisualiser les cas' }).click()
    await expect(modale.getByRole('heading', { name: '30 cas à créer' })).toBeVisible()
    await expect(modale.getByLabel('Nom du cas 1', { exact: true })).toHaveValue('Homonyme')
    await expect(modale.getByLabel('Nom du cas 2', { exact: true })).toHaveValue('Homonyme (2)')
    await modale.getByLabel('Nom du cas 2', { exact: true }).fill('Homonyme')
    await expect(modale.getByRole('button', { name: 'Créer les cas' })).toBeDisabled()
    await modale.getByRole('button', { name: 'Annuler', exact: true }).click()
    expect(readFileSync(fichier, 'utf8')).toBe(avant)

    await modale.getByRole('button', { name: 'Nouveau cas' }).click()
    await modale.getByRole('radio', { name: 'Plusieurs personnes' }).check()
    await modale.getByRole('button', { name: 'Tout sélectionner', exact: true }).click()
    await modale.getByRole('button', { name: 'Prévisualiser les cas' }).click()
    await modale.getByRole('button', { name: 'Créer les cas' }).click()
    await expect(modale.locator('.carte-cas')).toHaveCount(30)
    expect(Object.values(JSON.parse(readFileSync(fichier, 'utf8')).cas)).toHaveLength(30)

    await modale.getByRole('button', { name: 'Nouveau cas' }).click()
    await modale.getByRole('radio', { name: 'Plusieurs personnes' }).check()
    await modale.getByRole('button', { name: 'Tout sélectionner', exact: true }).click()
    await modale.getByRole('radio', { name: 'Un cas collectif' }).check()
    await modale.getByRole('button', { name: 'Prévisualiser les cas' }).click()
    await expect(modale.getByRole('heading', { name: '1 cas à créer' })).toBeVisible()
    await modale.getByLabel('Nom du cas 1', { exact: true }).fill('Collectif des trente')
    await modale.getByRole('button', { name: 'Créer les cas' }).click()
    await expect(modale.locator('.carte-cas')).toHaveCount(31)
    const apres = JSON.parse(readFileSync(fichier, 'utf8'))
    expect((Object.values(apres.cas).find((cas: any) => cas.nom === 'Collectif des trente') as any).regles[0].membres).toHaveLength(30)
    expect(readFileSync(source, 'utf8')).toBe(sourceAvant)
    await app.close()
    app = await lancer(userDataDir)
    page = await app.firstWindow()
    await entrerCorpus(page)
    await page.locator('.btn-cas').click()
    modale = page.locator('.modale-cas')
    await expect(modale.locator('.carte-cas')).toHaveCount(31)
    expect(JSON.parse(readFileSync(fichier, 'utf8')).cas).toEqual(apres.cas)
  } finally {
    await app.close()
    rmSync(userDataDir, { recursive: true, force: true })
  }
})

test('entretiens entiers : individuel, collectif, source vide et futurs paragraphes sans repères', async () => {
  const userDataDir = mkdtempSync(join(tmpdir(), 'sonal-cas-entiers-'))
  let app = await lancer(userDataDir)
  try {
    let page = await app.firstWindow()
    await entrerCorpus(page)
    await page.evaluate(async () => { await (window as any).sonal.corpus.creerEntretienVide('Source sans texte') })
    await app.close()
    app = await lancer(userDataDir)
    page = await app.firstWindow()
    await entrerCorpus(page)
    await page.locator('.btn-cas').click()
    let modale = page.locator('.modale-cas')
    await modale.getByRole('button', { name: 'Nouveau cas' }).click()
    await modale.getByRole('radio', { name: 'Depuis des entretiens' }).check()
    await modale.getByRole('button', { name: 'Tout sélectionner', exact: true }).click()
    await modale.getByRole('button', { name: 'Prévisualiser les cas' }).click()
    await expect(modale.getByRole('heading', { name: '2 cas à créer' })).toBeVisible()
    await modale.getByRole('button', { name: 'Créer les cas' }).click()
    await expect(modale.locator('.carte-cas')).toHaveCount(2)
    await modale.locator('.carte-cas').filter({ hasText: 'Source sans texte' }).click()
    await expect(modale).toContainText('Cet entretien ne contient pas encore de texte.')
    await expect(modale.locator('.metriques')).toContainText('0 passage(s)')
    await expect(modale.locator('.metriques')).toContainText('1 source(s)')

    await modale.getByRole('button', { name: 'Nouveau cas' }).click()
    await modale.getByRole('radio', { name: 'Depuis des entretiens' }).check()
    await modale.getByRole('button', { name: 'Tout sélectionner', exact: true }).click()
    await modale.getByRole('radio', { name: 'Un cas collectif' }).check()
    await modale.getByRole('button', { name: 'Prévisualiser les cas' }).click()
    await modale.getByLabel('Nom du cas 1', { exact: true }).fill('Toutes les sources')
    await modale.getByRole('button', { name: 'Créer les cas' }).click()
    await expect(modale.locator('.passage-cas')).toHaveCount(2)
    await expect(modale.locator('.passage-cas blockquote').first()).toContainText('travail passé')
    await modale.getByRole('combobox', { name: /Matériaux affichés/ }).selectOption('manuels')
    await expect(modale).toContainText('Aucun ajout manuel dans ce cas.')
    const fichier = join(userDataDir, 'corpus', 'corpus.json')
    const avant = JSON.parse(readFileSync(fichier, 'utf8')).cas
    await app.close()
    const cheminSource = join(userDataDir, 'corpus', 'entretiens', 'e1.json')
    const source = JSON.parse(readFileSync(cheminSource, 'utf8'))
    expect(source.reperesPassages ?? []).toEqual([])
    source.corpsTexte.content.push({ type: 'paragraph', attrs: { loc: null }, content: [{ type: 'text', text: 'Paragraphe ajouté après la création.' }] })
    source.lastModified = new Date().toISOString()
    writeFileSync(cheminSource, JSON.stringify(source))
    app = await lancer(userDataDir)
    page = await app.firstWindow()
    await entrerCorpus(page)
    await page.locator('.btn-cas').click()
    modale = page.locator('.modale-cas')
    await modale.locator('.carte-cas').filter({ hasText: 'Toutes les sources' }).click()
    await expect(modale.locator('.passage-cas blockquote').first()).toContainText('Paragraphe ajouté après la création.')
    expect(JSON.parse(readFileSync(fichier, 'utf8')).cas).toEqual(avant)
  } finally {
    await app.close()
    rmSync(userDataDir, { recursive: true, force: true })
  }
})
