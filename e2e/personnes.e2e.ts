import { test, expect } from '@playwright/test'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { entrerCorpus, lancer } from './util'

test('Personnes : créer, renommer, lier deux entretiens, ouvrir et délier', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'sonal-personnes-e2e-'))
  const app = await lancer(dir)
  try {
    const page = await app.firstWindow()
    await entrerCorpus(page)
    await page.evaluate(async () => {
      const api = (window as any).sonal.corpus
      const { id } = await api.creerEntretienVide('Deuxième entretien')
      const lecture = await api.lireEntretien(id)
      const { formatVersion, lastModified, ...payload } = lecture.data
      payload.locuteurs = [{ id: 'loc-karine-2', index: 0, nom: 'Mme Dupont', valeursLoc: {}, personneRef: null }]
      await api.ecrireEntretien(id, payload)
    })
    await page.locator('.onglets-corpus').getByRole('button', { name: 'Personnes', exact: true }).click()
    const panneau = page.locator('.personnes-corpus')
    await expect(panneau).toBeVisible()
    await expect(page.locator('.grille-corpus')).toBeHidden()
    await expect(panneau.locator('.entete').getByRole('button', { name: 'Aide sur l’onglet Personnes' })).toBeVisible()
    await expect(panneau.locator('.repertoire > .carte-repertoire')).toHaveCount(4)
    const carteRepertoire = panneau.locator('details.carte-personnes')
    await expect(carteRepertoire).toHaveAttribute('open', '')
    await carteRepertoire.locator('summary').click()
    await expect(carteRepertoire).not.toHaveAttribute('open', '')
    await carteRepertoire.locator('summary').click()
    await expect(panneau).toContainText('Aucune personne n’est encore identifiée')
    await panneau.getByRole('button', { name: 'Karine', exact: true }).click()
    await panneau.getByLabel('Nouvelle personne').fill('Karine Dupont')
    await panneau.getByRole('button', { name: 'Créer', exact: true }).click()
    await expect(panneau.getByRole('heading', { name: 'Personne · Karine Dupont' })).toBeVisible()
    await panneau.getByLabel('Nom de référence').fill('K. Dupont')
    await panneau.getByLabel('Nom de référence').press('Enter')
    await expect(panneau.getByRole('heading', { name: 'Personne · K. Dupont' })).toBeVisible()
    await expect(carteRepertoire.getByRole('button', { name: 'K. Dupont (1 entretien)', exact: true })).toBeVisible()
    await expect(panneau.locator('.liens')).toContainText('Entretien Karine · Karine')
    await panneau.getByRole('button', { name: 'Mme Dupont', exact: true }).click()
    const id = await page.evaluate(async () => (await (window as any).sonal.corpus.personnesInventaire()).personnes[0].id)
    await panneau.getByLabel('Associer à').selectOption(id)
    await panneau.getByRole('button', { name: 'Associer', exact: true }).click()
    await expect(panneau.getByRole('dialog')).toContainText('Mme Dupont')
    await panneau.getByRole('button', { name: 'Confirmer', exact: true }).click()
    await expect(panneau).toHaveAttribute('aria-busy', 'false')
    await expect(panneau.getByRole('alert')).toHaveCount(0)
    await panneau.locator('.repertoire').getByRole('button', { name: /K\. Dupont/ }).click()
    await expect(panneau.locator('.liens li')).toHaveCount(2)
    await panneau.locator('.liens li').filter({ hasText: 'Entretien Karine' }).getByRole('button', { name: 'Ouvrir l’entretien' }).click()
    await expect(page.locator('.entretien-ecran')).toBeVisible()
    await expect(page.getByText('Lié à « K. Dupont » — le nom saisi reste local.', { exact: true })).toHaveCount(0)
    await expect(page.locator('.entretien-ecran button[data-onglet="locuteurs"].actif')).toHaveAttribute('title', 'Locuteurs')
    await page.locator('.entretien-ecran button[data-onglet="notes"]').click()
    const formulaireNote = page.locator('.nouvelle-note-inline')
    await formulaireNote.locator('.champ-titre-note input').fill('Identité vérifiée')
    await formulaireNote.locator('.options-avancees-note summary').click()
    await page.getByRole('group', { name: 'Concerne (optionnel)' }).getByRole('checkbox', { name: 'Karine' }).check()
    await formulaireNote.getByRole('button', { name: 'Créer une note', exact: true }).click()
    // Retour au corpus par le fil d'Ariane (pas de bouton « ← Corpus » dans la barre).
  await page.locator('.fil .lien-nav', { hasText: 'Corpus' }).click()
    await expect(panneau).toBeVisible()
    await expect(panneau.getByRole('heading', { name: 'Personne · K. Dupont' })).toBeVisible()
    await expect(panneau.getByText('Notes liées (1)')).toBeVisible()
    await panneau.getByText('Notes liées (1)').click()
    await expect(panneau.getByText('Identité vérifiée')).toBeVisible()
    await panneau.getByRole('button', { name: 'Ouvrir l’entretien dans Notes' }).click()
    await expect(page.locator('.entretien-ecran button[data-onglet="notes"].actif')).toHaveAttribute('title', 'Notes')
    // Retour au corpus par le fil d'Ariane (pas de bouton « ← Corpus » dans la barre).
  await page.locator('.fil .lien-nav', { hasText: 'Corpus' }).click()
    await expect(panneau).toHaveAttribute('aria-busy', 'false')
    await panneau.locator('.liens li').filter({ hasText: 'Entretien Karine' }).getByRole('button', { name: 'Modifier l’association…', exact: true }).click()
    await panneau.getByRole('button', { name: 'Ne plus associer', exact: true }).click()
    await panneau.getByRole('button', { name: 'Annuler', exact: true }).click()
    await expect(panneau.getByRole('button', { name: 'Ne plus associer', exact: true })).toBeVisible()
    await panneau.getByRole('button', { name: 'Ne plus associer', exact: true }).click()
    await panneau.getByRole('button', { name: 'Confirmer', exact: true }).click()
    await expect(panneau).toHaveAttribute('aria-busy', 'false')
    await panneau.locator('.repertoire').getByRole('button', { name: /K\. Dupont/ }).click()
    await expect(panneau.locator('.liens li')).toHaveCount(1)
    await expect(panneau.locator('.repertoire').getByRole('button', { name: 'Karine', exact: true })).toBeVisible()
    await panneau.locator('.repertoire').getByRole('button', { name: 'Karine', exact: true }).click()
    await panneau.getByRole('button', { name: 'Ouvrir l’entretien', exact: true }).click()
    await expect(page.locator('.lien-personne-loc')).toHaveCount(0)
    const indexKarine = await page.locator('.nom-loc').evaluateAll(inputs => inputs.findIndex(input => (input as HTMLInputElement).value === 'Karine'))
    expect(indexKarine).toBeGreaterThanOrEqual(0)
    const nomKarine = page.locator('.nom-loc').nth(indexKarine)
    await nomKarine.fill('Karine Durand')
    await nomKarine.press('Tab')
    // Retour au corpus par le fil d'Ariane (pas de bouton « ← Corpus » dans la barre).
  await page.locator('.fil .lien-nav', { hasText: 'Corpus' }).click()
    const apresDeliaison = await page.evaluate(async () => (window as any).sonal.corpus.personnesInventaire())
    expect(apresDeliaison.personnes).toHaveLength(1)
    expect(apresDeliaison.locuteurs.find((l: any) => l.nom === 'Karine Durand').personneRef).toBeNull()
    const separateur = panneau.getByRole('separator')
    const avant = Number(await separateur.getAttribute('aria-valuenow'))
    await separateur.focus()
    await page.keyboard.press('ArrowRight')
    await expect(separateur).toHaveAttribute('aria-valuenow', String(avant + 20))
    await page.setViewportSize({ width: 650, height: 850 })
    await expect(panneau.locator('.deux-colonnes')).toHaveClass(/verticale/)
  } finally {
    await app.close()
    rmSync(dir, { recursive: true, force: true })
  }
})
